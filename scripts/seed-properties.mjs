const seedProperties = async () => {
  console.log(`Seeding ${propertyListings.length} property listings into "house_listings" collection...`);

  for (const listing of propertyListings) {
    try {
      const ref = doc(db, 'house_listings', listing.id);
      const payload = {
        ...listing,
        createdAt: Timestamp.fromDate(new Date(listing.listedOn || Date.now())),
        updatedAt: Timestamp.now(),
      };
      delete payload.id;
      await setDoc(ref, payload);
      console.log(`  ✔ ${listing.title}  (${listing.propertySubType}, ${listing.price})`);
    } catch (error) {
      console.error(`  ❌ Failed for ${listing.id}:`, error.message || error);
    }
  }

  console.log('\nDone! Property listings are seeded. They should now appear in:');
  console.log('  • Admin Dashboard → Properties');
  console.log('  • Web → Airbnb & Rentals (/airbnb)');
  console.log('  • Web → House Listings (/house-listings)');
  console.log('  • Mobile App → Property & Stay screens');
  process.exit(0);
};

seedProperties();
